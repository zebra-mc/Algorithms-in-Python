# текст для пункта 2
EXPLANATION = """\
Чтобы работать с цифрами, хватает двух операций: n % 10 дает последнюю цифру
числа, n // 10 ее убирает.
Можно было бы перевернуть число целиком и сравнить с исходным, но достаточно
перевернуть половину. На каждом шаге одна цифра переезжает из head (левая, еще
не разобранная часть) в tail (перевернутая правая часть).
Цикл идет, пока head > tail. С каждым шагом в head становится на цифру меньше,
а в tail на цифру больше, поэтому примерно за половину от общего количества
цифр цикл заканчивается: в head остается левая часть числа, в tail - правая.
Дальше два случая. Если цифр четное количество, половины должны совпасть:
head == tail. Если нечетное, то в tail попала еще и средняя цифра, у нее нет
пары и на ответ она не влияет, поэтому сравниваем head == tail // 10.
Отдельно отсекаем числа с нулем на конце. Первая цифра числа нулем быть не
может, значит палиндромом такое число не будет. Проверка нужна потому, что
ноль, ушедший в tail первым, там не сохраняется: ведущих нулей у чисел нет.
Правая половина оказывается короче, чем должна быть, и сравнение врет. Так,
на 10 цикл закончится при head = 0 и tail = 1, проверка head == tail // 10
даст 0 == 0, и ответ будет True. На 110 то же самое: head = 1, tail = 1."""

