COMPLEXITY = """\
Обозначения: n - само число, поданное на вход, d - количество цифр в его
десятичной записи. Эти величины связаны как d = log10(n) + 1, округленное вниз.
Логарифм по основанию 10, потому что цифры отрезаются делением на 10.
Время: O(log10 n), то есть O(d). Цикл делает примерно d/2 шагов, на каждом
выполняется несколько арифметических операций. Переворот половины числа вместо
целого экономит время вдвое, но асимптотику не меняет.
Память: O(1). Две переменные, head и tail, независимо от размера числа."""

