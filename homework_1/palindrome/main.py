def action_run():
    n = read_number("Введите целое положительное число: ")          # запрашиваем данные
    if n is None:                                                   # ввод не подошел
        print("Некорректный ввод: нужно целое положительное число")  # сообщаем причину
        return                                                      # возвращаемся в меню
    print(is_palindrome(n))                                         # печатаем True или False

def action_explanation():
    print(EXPLANATION)                  # выводим готовый текст

def action_complexity():
    print(COMPLEXITY)                   # выводим готовый текст

def action_visualization():
    s = input("Число для разбора (Enter - взять 1234321): ").strip()    # можно задать свой пример
    if s == "":                                                         # ничего не ввели
        n = 1234321                                                     # берем пример по умолчанию
    elif not s.isdigit() or int(s) < 1:                                 # ввели не то
        print("Некорректный ввод: нужно целое положительное число")     # сообщаем причину
        return                                                          # возвращаемся в меню
    else:                                                               # ввели нормальное число
        n = int(s)                                                      # с ним и работаем
    print()                                                             # пустая строка перед таблицей
    print(f"{'шаг':>4} {'head':>12} {'tail':>12}  комментарий")         # шапка таблицы
    if n % 10 == 0:                                                     # сработало раннее отсечение
        print(f"{'-':>4} {n:>12} {0:>12}  оканчивается на 0, цикл не нужен")   # единственная строка
        print("\nОтвет: False")                                         # и сразу ответ
        return                                                          # цикл не выполняется
    head, tail, step = n, 0, 0                                          # начальные значения и счетчик шагов
    print(f"{'-':>4} {head:>12} {tail:>12}  начало")                    # состояние до цикла
    while head > tail:                                                  # тот же цикл, что в решении
        step += 1                                                       # пошел очередной шаг
        digit = head % 10                                               # цифра, которая сейчас переедет
        tail = tail * 10 + digit                                        # дописываем ее к tail
        head //= 10                                                     # и убираем из head
        print(f"{step:>4} {head:>12} {tail:>12}  перенесли цифру {digit}")   # состояние после шага
    print(f"{step + 1:>4} {head:>12} {tail:>12}  head > tail больше не верно, выход")   # выход из цикла
    if head == tail:                                                    # цифр было четное количество
        print(f"\nhead == tail: {head} == {tail}, цифр четное число. Ответ: True")
    elif head == tail // 10:                                            # цифр было нечетное количество
        print(f"\nhead == tail // 10: {head} == {tail // 10}, "
              f"средняя цифра лишняя. Ответ: True")
    else:                                                               # ни одна проверка не прошла
        print(f"\n{head} != {tail} и {head} != {tail // 10}. Ответ: False")

def action_tests():
    suite = unittest.TestLoader().loadTestsFromTestCase(Tests)   # собираем все методы test_*
    unittest.TextTestRunner(verbosity=2).run(suite)              # запускаем и печатаем отчет

class Tests(unittest.TestCase):

    def test_palindromes(self):
        """Обычные палиндромы четной и нечетной длины"""
        for n in (7, 11, 121, 1221, 12321, 909, 1234321):   # палиндромы разной длины
            self.assertTrue(is_palindrome(n), n)            # ожидаем True

    def test_not_palindromes(self):
        """Обычные непалиндромы"""
        for n in (12, 31, 123, 1231, 12345, 1002):          # заведомо несимметричные числа
            self.assertFalse(is_palindrome(n), n)           # ожидаем False

    def test_one_digit(self):
        """Граница: однозначное число симметрично само себе"""
        for n in (1, 5, 9):                                 # минимально возможный вход
            self.assertTrue(is_palindrome(n), n)            # ожидаем True

    def test_trailing_zero(self):
        """Граница: ноль в конце, на нем ломается схема без отсечения"""
        for n in (10, 110, 1200, 1000000):                  # первая цифра не нулевая, последняя нулевая
            self.assertFalse(is_palindrome(n), n)           # ожидаем False

    def test_middle_digit(self):
        """Средняя цифра пары не имеет, крайние имеют"""
        self.assertTrue(is_palindrome(1235321))             # поменяли только середину
        self.assertFalse(is_palindrome(1234322))            # поменяли последнюю цифру

    def test_zeros_inside(self):
        """Нули внутри числа не мешают симметрии"""
        self.assertTrue(is_palindrome(1200021))             # нули стоят симметрично
        self.assertTrue(is_palindrome(10000001))            # четная длина, нули посередине
        self.assertFalse(is_palindrome(1000021))            # похоже на палиндром, но не он

    def test_big_numbers(self):
        """Длинные числа в 61 цифру"""
        n = 7 * 10 ** 60 + 7                                # семерка, 59 нулей, семерка
        self.assertTrue(is_palindrome(n))                   # запись симметрична
        self.assertTrue(is_palindrome(n + 10 ** 30))        # поменяли среднюю цифру
        self.assertFalse(is_palindrome(n + 10 ** 29))       # сместили ее, симметрия сломалась

    def test_against_full_reverse(self):
        """Сверка с наивным способом на всех числах до 10000"""
        for n in range(1, 10000):                           # перебираем весь диапазон
            rev, m = 0, n                                   # rev - число задом наперед
            while m > 0:                                    # пока остались цифры
                rev = rev * 10 + m % 10                     # переносим младшую цифру в rev
                m //= 10                                    # и убираем ее из m
            self.assertEqual(is_palindrome(n), n == rev, n)  # ответы обязаны совпасть

    def test_read_number(self):
        """Корректность ввода: принимается только целое положительное число

        Настоящего ввода с клавиатуры в тестах нет, поэтому на время проверки
        закрываем имя input одноименной глобальной переменной модуля.
        """
        global input                                        # подменять будем глобальное имя
        cases = {                                           # строка ввода -> что должно вернуться
            "1": 1,                                         # минимально допустимый ввод
            "42": 42,                                       # обычный случай
            "  7  ": 7,                                     # пробелы по краям срезаются
            "0": None,                                      # ноль неположителен
            "": None,                                       # пустая строка
            "-5": None,                                     # минус не цифра
            "3.14": None,                                   # точка не цифра
            "abc": None,                                    # буквы вместо цифр
        }
        try:                                                # подмену надо снять в любом случае
            for text, expected in cases.items():            # проверяем вводы по очереди
                input = lambda prompt, s=text: s            # вместо чтения с клавиатуры отдаем s
                self.assertEqual(read_number("> "), expected, text)   # ответ совпал с ожидаемым
        finally:                                            # даже если проверка не прошла
            del input                                       # имя убрали, снова работает встроенный input

# меню

MENU = {
    "1": ("Запуск", action_run),                                    # ввод данных и ответ
    "2": ("Объяснение решения", action_explanation),                # описание алгоритма
    "3": ("Оценка сложности", action_complexity),                   # время и память
    "4": ("Визуализация работы алгоритма", action_visualization),   # таблица по шагам
    "5": ("Тесты", action_tests),                                   # прогон тестов
}

def main():
    while True:                                     # меню показывается, пока не выбран выход
        print("\n" + TITLE)                         # заголовок задачи
        for number, (name, _) in MENU.items():      # перебираем пункты по порядку
            print(f"{number}. {name}")              # печатаем номер и название
        print("6. Выход")                           # последний пункт обрабатывается отдельно
        choice = input("Выберите пункт: ").strip()  # читаем номер пункта
        if choice == "6":                           # выбран выход
            break                                   # выходим из цикла, программа завершается
        if choice not in MENU:                      # введено что-то постороннее
            print("Такого пункта нет")              # предупреждаем
            continue                                # и показываем меню заново
        print()                                     # отступ перед выводом пункта
        MENU[choice][1]()                           # вызываем функцию выбранного пункта

if __name__ == "__main__":                          # запуск только при прямом вызове файла
    main()                                          # стартуем меню
