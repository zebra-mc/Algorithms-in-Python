import unittest                         # стандартный модуль для тестов

TITLE = "Задача 1. Палиндром"           # заголовок, который печатается над меню

# решение

def is_palindrome(n):
    """n - целое положительное. True, если его запись читается одинаково в обе стороны.

    Цифры достаем арифметикой: n % 10 - последняя цифра, n // 10 - число без нее.
    Переворачиваем не все число, а только правую половину, и сравниваем с левой.
    """
    if n % 10 == 0:                     # последняя цифра нулевая, а первая нет
        return False                    # такое число палиндромом быть не может
    head = n                            # левая часть числа, еще не разобранная
    tail = 0                            # правая часть числа, уже перевернутая
    while head > tail:                  # пока в head цифр больше, чем в tail
        tail = tail * 10 + head % 10    # младшую цифру head дописываем к tail
        head //= 10                     # и убираем ее из head
    return head == tail or head == tail // 10   # цифр четное число либо нечетное

def read_number(prompt):
    """Читает положительное целое. Возвращает None, если ввод некорректный."""
    s = input(prompt).strip()           # читаем строку и убираем пробелы по краям
    if not s.isdigit() or int(s) < 1:   # буквы, минус, пустая строка, неположительное
        return None                     # признак некорректного ввода
    return int(s)                       # корректное положительное число

