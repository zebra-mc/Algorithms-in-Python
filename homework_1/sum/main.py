def action_tests():
    suite = unittest.TestLoader().loadTestsFromTestCase(Tests)   # собираем все методы test_*
    unittest.TextTestRunner(verbosity=2).run(suite)              # запускаем и печатаем отчет

class Tests(unittest.TestCase):

    def test_examples(self):
        """Примеры из условия"""
        self.assertEqual(max_even_sum([5, 7, 13, 2, 14]), 36)   # берем 2, 7, 13, 14
        self.assertEqual(max_even_sum([3]), 0)                  # 3 нечетное, берем пустое подмножество

    def test_sum_already_even(self):
        """Сумма четная сразу, ответ равен сумме всего массива"""
        self.assertEqual(max_even_sum([2, 4, 6]), 12)           # нечетных нет вообще
        self.assertEqual(max_even_sum([7, 9]), 16)              # нечетных четное количество

    def test_drops_smallest_odd(self):
        """Сумма нечетная, выбрасывается ровно один нечетный элемент"""
        self.assertEqual(max_even_sum([9, 4, 6, 3, 8, 5]), 32)  # 35 - 3, пример из визуализации
        self.assertEqual(max_even_sum([99, 3, 1, 2]), 104)      # выбрасываем 1, а не первый нечетный 99

    def test_one_element(self):
        """Граница: массив из одного элемента"""
        self.assertEqual(max_even_sum([2]), 2)                  # четный элемент берем
        self.assertEqual(max_even_sum([7]), 0)                  # нечетный брать нельзя

    def test_empty(self):
        """Граница: пустой массив, сумма пустого подмножества ноль"""
        self.assertEqual(max_even_sum([]), 0)                   # цикл не выполняется ни разу

    def test_all_odd(self):
        """Граница: нечетных элементов четное и нечетное количество"""
        self.assertEqual(max_even_sum([1, 3, 5, 7]), 16)        # выбрасывать нечего
        self.assertEqual(max_even_sum([1, 3, 5]), 8)            # 9 - 1

    def test_duplicates_of_min_odd(self):
        """Минимальный нечетный встречается несколько раз, убираем одну копию"""
        self.assertEqual(max_even_sum([1, 1, 1, 4]), 6)         # 7 - 1, две единицы остаются

    def test_big_numbers(self):
        """Длинные числа, переполнения в Python нет"""
        self.assertEqual(max_even_sum([10 ** 18, 10 ** 18 + 1]), 10 ** 18)   # сумма нечетная
        self.assertEqual(max_even_sum([10 ** 18, 10 ** 18]), 2 * 10 ** 18)   # сумма четная

    def test_parse_numbers(self):
        """Разбор строки: нормальный ввод и мусор"""
        self.assertEqual(parse_numbers("5 7 13 2 14"), [5, 7, 13, 2, 14])   # пример из условия
        self.assertEqual(parse_numbers("  4   6  "), [4, 6])                # лишние пробелы
        self.assertIsNone(parse_numbers(""))                                # пустая строка
        self.assertIsNone(parse_numbers("4 -6"))                            # отрицательное число
        self.assertIsNone(parse_numbers("4 x"))                             # буква вместо числа
        self.assertIsNone(parse_numbers("4 0"))                             # ноль не положительный

    def test_against_brute_force(self):
        """Сверка с полным перебором подмножеств на случайных массивах"""
        rnd = random.Random(42)                             # фиксируем seed, тест воспроизводим
        for _ in range(300):                                # 300 случайных массивов
            arr = [rnd.randint(1, 50) for _ in range(rnd.randint(0, 10))]   # длина до 10, иначе перебор долгий
            best = 0                                        # лучшая четная сумма перебором
            for size in range(len(arr) + 1):                # все размеры подмножеств
                for subset in combinations(arr, size):      # все подмножества данного размера
                    s = sum(subset)                         # сумма подмножества
                    if s % 2 == 0 and s > best:             # четная и рекордная
                        best = s                            # запоминаем
            self.assertEqual(max_even_sum(arr), best, arr)  # ответы обязаны совпасть

    def test_invariants(self):
        """Ответ всегда четный и не превышает суммы всего массива"""
        rnd = random.Random(7)                              # другой seed
        for _ in range(300):                                # 300 случайных массивов
            arr = [rnd.randint(1, 10 ** 6) for _ in range(rnd.randint(1, 100))]   # тут длина уже любая
            result = max_even_sum(arr)                      # ответ алгоритма
            self.assertEqual(result % 2, 0, arr)            # делится на 2
            self.assertTrue(0 <= result <= sum(arr), arr)   # лежит между нулем и полной суммой

