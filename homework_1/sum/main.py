# решение

def max_even_sum(numbers):
    """numbers - целые положительные. Максимальная сумма элементов, кратная 2.

    Считаем сумму всех чисел. Если она четная, это и есть ответ. Если нечетная,
    вычитаем самый маленький нечетный элемент - минимальную возможную потерю.
    """
    total = 0                           # сумма всех элементов
    min_odd = None                      # самый маленький нечетный элемент
    for x in numbers:                   # один проход по массиву
        total += x                      # копим сумму
        if x % 2 != 0 and (min_odd is None or x < min_odd):   # нечетный и меньше найденного
            min_odd = x                 # обновляем минимум
    if total % 2 == 0:                  # сумма уже четная
        return total                    # больше взять нечего, все числа положительные
    return total - min_odd              # иначе выбрасываем один нечетный, самый дешевый

def parse_numbers(s):
    """Разбирает строку вида '5 7 13 2 14'. None, если ввод некорректный."""
    parts = s.split()                           # режем строку по пробелам
    if not parts:                               # пустая строка, чисел нет
        return None                             # признак некорректного ввода
    for token in parts:                         # проверяем каждый элемент
        if not token.isdigit() or int(token) < 1:   # буквы, минус, ноль, дробь
            return None                         # признак некорректного ввода
    return [int(token) for token in parts]      # корректный массив чисел

def read_numbers(prompt):
    """Читает массив положительных целых через пробел. None, если ввод некорректный."""
    return parse_numbers(input(prompt))         # вся проверка живет в parse_numbers

