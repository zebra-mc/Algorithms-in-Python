EXPLANATION = """\
Четность суммы зависит только от того, сколько нечетных слагаемых в нее вошло:
четные ничего не меняют, а каждое нечетное переключает четность. Значит сумма
четна тогда и только тогда, когда нечетных элементов взято четное количество.
Отсюда два случая.
Если сумма всего массива четная, это и есть ответ. Числа положительные, поэтому
любое выброшенное слагаемое только уменьшает результат, а взять что-то сверх
всего массива нельзя.
Если сумма всего массива нечетная, значит нечетных элементов нечетное число.
Чтобы вернуть четность, надо выбросить подмножество с нечетной суммой, то есть
нечетное количество нечетных элементов: один, три, пять и так далее. Выбросить
три всегда хуже, чем один, потому что все числа положительные. Значит убираем
ровно один нечетный элемент, и из них - самый маленький.
Реализация ровно это и делает за один проход: копит total и попутно запоминает
минимум среди нечетных. Если total оказалась нечетной, нечетный элемент в
массиве точно был, поэтому min_odd к этому моменту не None и вычитание корректно."""

