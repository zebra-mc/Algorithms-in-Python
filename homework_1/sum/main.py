COMPLEXITY = """\
Обозначение: n - количество элементов массива.
Время: O(n). Один проход по массиву, на каждом элементе константное число
операций: сложение, проверка остатка и сравнение с текущим минимумом. Ни
сортировка, ни повторные проходы не нужны, потому что сумма и минимум по
нечетным считаются одновременно.
Память: O(1). Две переменные, total и min_odd, независимо от длины массива.
Сам массив занимает O(n), но это память под входные данные, а не под алгоритм:
функции достаточно итератора, весь массив в памяти держать не обязательно."""

