def print_state(sieve, n, per_line=20):
    """Печатает текущее решето: уцелевшие числа как есть, вычеркнутые точкой."""
    for start in range(2, n, per_line):                     # режем на строки по per_line чисел
        chunk = range(start, min(start + per_line, n))      # числа очередной строки
        cells = (f"{i:>3}" if sieve[i] else f"{'.':>3}" for i in chunk)   # 1 - число, 0 - точка
        print("   " + " ".join(cells))                      # отступ и сама строка

def action_visualization():
    s = input("N для разбора (Enter - взять 30): ").strip()             # можно задать свой пример
    if s == "":                                                         # ничего не ввели
        n = 30                                                          # берем пример по умолчанию
    elif not s.isdigit():                                               # ввели не то
        print("Некорректный ввод: нужно целое неотрицательное число")   # сообщаем причину
        return                                                          # возвращаемся в меню
    else:                                                               # ввели нормальное число
        n = int(s)                                                      # с ним и работаем
    if n > 200:                                                         # решето не влезет в экран
        print("Для наглядности возьмите N не больше 200")               # просим число поменьше
