# решение

def count_primes(n):
    """n - целое. Возвращает количество простых чисел, строго меньших n.

    Решето Эратосфена. Заводим массив длиной n, индекс в нем - само число.
    Считаем все числа простыми, а потом вычеркиваем кратные каждому уцелевшему.
    Что осталось невычеркнутым, то и простое.
    """
    if n <= 2:                          # меньше 2 простых чисел не существует
        return 0                        # сюда попадают 0, 1, 2 и все отрицательные
    sieve = bytearray([1]) * n          # sieve[i] == 1 значит, что i пока считаем простым
    sieve[0] = sieve[1] = 0             # 0 и 1 простыми не являются по определению
    i = 2                               # первый кандидат
    while i * i < n:                    # делители больше корня перебирать незачем
        if sieve[i]:                    # i уцелело, значит оно простое
            start = i * i               # меньшие кратные вычеркнуты на прошлых шагах
            count = (n - start + i - 1) // i    # сколько кратных i попадет в решето
            sieve[start::i] = bytearray(count)  # нули на местах start, start + i, ...
        i += 1                          # переходим к следующему кандидату
    return sum(sieve)                   # единицы остались только у простых чисел

def read_number(prompt):
    """Читает целое число. Возвращает None, если ввод некорректный."""
    s = input(prompt).strip()           # читаем строку и убираем пробелы по краям
    body = s[1:] if s.startswith("-") else s    # минус допустим, дальше должны идти цифры
    if not body.isdigit():              # буквы, точка, пустая строка, двойной минус
        return None                     # признак некорректного ввода
    return int(s)                       # корректное целое число

